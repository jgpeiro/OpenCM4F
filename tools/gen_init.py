"""Turns the ROM images into Verilog include files with initial assignments, so no tool has to find a
$readmemh file (zero entries are left out: block RAMs start at 0).
usage: gen_init.py roms              rtl/soc/rom/*.hex   -> rtl/soc/init_{font_s,font_l,icons,widths,rec}.vh
       gen_init.py fw <firmware.bin> fw/firmware.bin    -> rtl/soc/init_rom.vh (code ROM, 32-bit words)
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = f'{ROOT}/rtl/soc'


def write(name, mem, width, values, note='do not edit'):
    digits = (width + 3) // 4
    lines = [f'// generated by tools/gen_init.py - {note}']
    for i, v in enumerate(values):
        if v:
            lines.append(f"{mem}[{i}] = {width}'h{v:0{digits}x};")
    open(f'{R}/{name}', 'w').write('\n'.join(lines) + '\n')


def hexvals(path):
    return [int(x, 16) for x in open(path).read().split()]


if sys.argv[1:2] == ['roms']:
    write('init_font_s.vh', 'font_s', 4, hexvals(f'{R}/rom/font_s.hex'))
    write('init_font_l.vh', 'font_l', 4, hexvals(f'{R}/rom/font_l.hex'))
    write('init_icons.vh', 'icons', 4, hexvals(f'{R}/rom/icons.hex'))
    write('init_widths.vh', 'widths', 5, hexvals(f'{R}/rom/widths.hex'))
    write('init_rec.vh', 'rec', 16, hexvals(f'{R}/rom/rec.hex'))
elif sys.argv[1:2] == ['fw']:
    data = open(sys.argv[2], 'rb').read()
    data += bytes((-len(data)) % 4)
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    limit = int(sys.argv[3]) if len(sys.argv) > 3 else 8192
    assert len(words) <= limit, f'firmware too big: {len(data)} bytes > {4 * limit}'
    write('init_rom.vh', 'rom', 32, words, f'from {os.path.basename(sys.argv[2])}, {len(data)} bytes')
    print(f'init_rom.vh: {len(data)} bytes ({100 * len(words) / limit:.0f}% of the ROM)')
else:
    sys.exit(__doc__)
print('init files written')
