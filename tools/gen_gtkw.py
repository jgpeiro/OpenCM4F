"""Writes the GTKWave save files (tb/gtkw/*.gtkw) for the waves of the cocotb testbenches
(run.py --waves -> build/cocotb_<bench>_verilator/dump.fst). The signal names and widths are taken
from a dump, so the views always match the RTL.
usage: gen_gtkw.py <dump.fst of tb_core> <dump.fst of ocm4_fpu>"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'tb', 'gtkw')


def signals(fst):
    """full name -> width, from the VCD header of the dump"""
    vcd = subprocess.run(['fst2vcd', '-f', fst], capture_output=True, text=True).stdout
    scope, sig = [], {}
    for line in vcd.splitlines():
        t = line.split()
        if not t:
            continue
        if t[0] == '$scope':
            scope.append(t[2])
        elif t[0] == '$upscope':
            scope.pop()
        elif t[0] == '$var':
            name, width = t[4], int(t[2])
            if len(t) > 6 and t[5].startswith('['):
                name += t[5]                                 # gtkwave names vectors with their range
            if scope and scope[0].startswith('$'):
                continue                                     # $rootio: the top-level ports again
            sig['.'.join(scope + [name])] = width
        elif t[0] == '$enddefinitions':
            break
    return sig


def find(sig, path):
    """the dumped name for path (with or without a [msb:lsb] suffix)"""
    for n, w in sig.items():
        base = re.sub(r'\[\d+:\d+\]$', '', n)
        if base.endswith('.' + path) or base == path:
            return n, w
    return None, 0


def write(name, title, groups, sig, dumpfile):
    lines = [f'[*] OpenCM4F: {title}', f'[*] generated by tools/gen_gtkw.py', f'[dumpfile] "{dumpfile}"',
             '[timestart] 0', '[size] 1800 1000', '[pos] -1 -1', '*-20.0 0 -1', '[sst_width] 260',
             '[signals_width] 330', '[sst_expanded] 1', '[sst_vpaned_height] 300']
    missing = []
    for label, items in groups:
        lines += ['@200', f'-{label}']
        for it in items:
            fmt = None
            if isinstance(it, tuple):
                it, fmt = it
            n, w = find(sig, it)
            if not n:
                missing.append(it)
                continue
            flag = {'dec': '@24', 'sdec': '@424', 'bin': '@28', 'hex': '@22'}.get(fmt) or ('@28' if w == 1 else '@22')
            lines += [flag, n]
    open(os.path.join(OUT, name), 'w').write('\n'.join(lines) + '\n')
    print(f'{name}: {sum(len(g[1]) for g in groups) - len(missing)} signals', f'(missing: {missing})' if missing else '')


